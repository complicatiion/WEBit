using System.Text;
using WEBit.Core.Models;
using WEBit.Core.Serialization;
using WEBit.Core.Storage;

namespace WEBit.Service.Modules;

/// <summary>Writes the php.ini used by the PHP module (development defaults, mail to Mailpit).</summary>
public static class PhpIni
{
    private static readonly object WriteLock = new();

    /// <summary>Extensions in ext\ (php_*.dll) of the installed PHP, sorted; opcache is a zend extension.</summary>
    public static List<string> AvailableExtensions(string phpExe)
    {
        var extDir = Path.Combine(Path.GetDirectoryName(phpExe)!, "ext");
        if (!Directory.Exists(extDir))
        {
            return [];
        }

        return Directory.EnumerateFiles(extDir, "php_*.dll")
            .Select(f => Path.GetFileNameWithoutExtension(f)[4..].ToLowerInvariant())
            .Where(e => e is not ("opcache" or "xdebug"))
            .Order(StringComparer.Ordinal)
            .ToList();
    }

    /// <param name="xdebugDll">Xdebug for this php-cgi (step debugging on every request).</param>
    /// <param name="fileName">php.ini (default PHP) or php-8.2.ini, php-8.4-xdebug.ini … for additional processes.</param>
    public static string Write(WebitPaths paths, WebitSettings settings, string phpExe, string? xdebugDll = null, string fileName = "php.ini")
    {
        var target = Path.Combine(paths.PhpRuntimeDir, fileName);
        var phpDir = Path.GetDirectoryName(phpExe)!;
        var extDir = Path.Combine(phpDir, "ext");
        var sessions = Path.Combine(paths.PhpRuntimeDir, "sessions");
        var temp = Path.Combine(paths.PhpRuntimeDir, "tmp");
        Directory.CreateDirectory(sessions);
        Directory.CreateDirectory(temp);
        Directory.CreateDirectory(paths.LogsDir);

        var ini = new StringBuilder();
        ini.AppendLine("; Generated by WEBit at every module start – changes are overwritten.");
        ini.AppendLine("; Own settings: php.user.ini next to this file is appended.");
        ini.AppendLine("[PHP]");
        ini.AppendLine("engine = On");
        ini.AppendLine("short_open_tag = Off");
        ini.AppendLine("expose_php = Off");
        var php = settings.Php;
        ini.AppendLine($"max_execution_time = {php.MaxExecutionTime}");
        ini.AppendLine($"max_input_time = {Math.Max(60, php.MaxExecutionTime)}");
        ini.AppendLine($"memory_limit = {php.MemoryLimit}");
        ini.AppendLine("error_reporting = E_ALL");
        ini.AppendLine(php.DisplayErrors ? "display_errors = On" : "display_errors = Off");
        ini.AppendLine(php.DisplayErrors ? "display_startup_errors = On" : "display_startup_errors = Off");
        ini.AppendLine(settings.Logging.ModuleLogs ? "log_errors = On" : "log_errors = Off");
        ini.AppendLine($"error_log = \"{paths.PhpErrorLogFile}\"");
        ini.AppendLine($"post_max_size = {php.PostMaxSize}");
        ini.AppendLine($"upload_max_filesize = {php.UploadMaxFilesize}");
        ini.AppendLine("max_file_uploads = 50");
        ini.AppendLine($"upload_tmp_dir = \"{temp}\"");
        ini.AppendLine($"sys_temp_dir = \"{temp}\"");
        ini.AppendLine("default_charset = \"UTF-8\"");
        ini.AppendLine("cgi.fix_pathinfo = 1");
        ini.AppendLine("cgi.force_redirect = 0");
        ini.AppendLine($"extension_dir = \"{extDir}\"");
        foreach (var ext in php.EffectiveExtensions.Where(e => File.Exists(Path.Combine(extDir, $"php_{e}.dll"))))
        {
            ini.AppendLine($"extension = {ext}");
        }

        if (php.Opcache && File.Exists(Path.Combine(extDir, "php_opcache.dll")))
        {
            ini.AppendLine("zend_extension = opcache");
        }

        ini.AppendLine();
        ini.AppendLine("[opcache]");
        ini.AppendLine("; Edits must be visible at once.");
        ini.AppendLine(php.Opcache ? "opcache.enable = 1" : "opcache.enable = 0");
        ini.AppendLine("opcache.enable_cli = 0");
        ini.AppendLine("opcache.validate_timestamps = 1");
        ini.AppendLine("opcache.revalidate_freq = 0");
        ini.AppendLine();
        ini.AppendLine("[Date]");
        ini.AppendLine($"date.timezone = \"{TimeZoneId()}\"");
        ini.AppendLine();
        ini.AppendLine("[mail function]");
        ini.AppendLine("; Caught by the Mailpit module.");
        ini.AppendLine("SMTP = 127.0.0.1");
        ini.AppendLine($"smtp_port = {settings.MailpitSmtpPort}");
        ini.AppendLine("sendmail_from = webit@webit.test");
        ini.AppendLine();
        ini.AppendLine("[Session]");
        ini.AppendLine($"session.save_path = \"{sessions}\"");

        if (xdebugDll is not null)
        {
            ini.AppendLine();
            ini.AppendLine("[xdebug]");
            ini.AppendLine("; Only this php-cgi (sites with Xdebug switched on). IDE listens on 127.0.0.1.");
            ini.AppendLine($"zend_extension = \"{xdebugDll}\"");
            ini.AppendLine("xdebug.mode = debug,develop");
            ini.AppendLine("xdebug.start_with_request = yes");
            ini.AppendLine("xdebug.client_host = 127.0.0.1");
            ini.AppendLine($"xdebug.client_port = {php.XdebugPort}");
            ini.AppendLine("xdebug.log_level = 0");
        }

        var user = Path.Combine(paths.PhpRuntimeDir, "php.user.ini");
        if (File.Exists(user))
        {
            ini.AppendLine();
            ini.AppendLine("; ---- php.user.ini");
            ini.Append(File.ReadAllText(user));
        }

        // Module start and the PHP tools write it: one at a time, replaced atomically (php-cgi never reads half a file).
        Directory.CreateDirectory(paths.PhpRuntimeDir);
        lock (WriteLock)
        {
            var tempFile = target + "." + Guid.NewGuid().ToString("N")[..8] + ".tmp";
            try
            {
                File.WriteAllText(tempFile, ini.ToString(), WebitJson.Utf8NoBom);
                for (var attempt = 1; ; attempt++)
                {
                    try
                    {
                        File.Move(tempFile, target, overwrite: true);
                        break;
                    }
                    catch (Exception ex) when (ex is IOException or UnauthorizedAccessException && attempt < 10)
                    {
                        Thread.Sleep(50 * attempt);
                    }
                }
            }
            finally
            {
                if (File.Exists(tempFile))
                {
                    File.Delete(tempFile);
                }
            }
        }

        return target;
    }

    private static string TimeZoneId()
    {
        var local = TimeZoneInfo.Local.Id;
        if (TimeZoneInfo.TryConvertWindowsIdToIanaId(local, out var iana))
        {
            return iana;
        }

        return local.Contains('/') ? local : "UTC";
    }
}
